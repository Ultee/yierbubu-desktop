const {_electron:electron}=require('playwright-core');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {toggleIncome}=require('./income-menu.cjs');
(async()=>{
  const profile=await fs.mkdtemp(path.join(os.tmpdir(),'salary-pet-desktop-'));
  const errors=[];let application;
  const launch=async()=>{
    const env={...process.env,SALARY_PET_PROFILE:profile};delete env.ELECTRON_RUN_AS_NODE;
    const result=await electron.launch({args:[path.resolve('.')],env});
    result.on('window',page=>page.on('pageerror',e=>errors.push(e.message)));
    return result;
  };
  try{
    await fs.mkdir('test-results',{recursive:true});application=await launch();
    const settings=application.windows().find(p=>p.url().endsWith('settings.html'))??await application.waitForEvent('window',page=>page.url().endsWith('settings.html')).catch(()=>null);
    const form=settings||application.windows().find(p=>p.url().endsWith('settings.html'));
    assert.ok(form,'first launch should open setup');
    form.setDefaultTimeout(6000);
    await form.locator('#salary').fill('10000');
    await form.locator('#save').click();
    await form.locator('#notice').filter({hasText:'已保存'}).waitFor();
    await form.locator('#end').fill('08:00');await form.locator('#save').click();
    await form.locator('[data-error="end"]').filter({hasText:'晚于'}).waitFor();
    await form.locator('#end').fill('18:00');await form.locator('#save').click();
    await form.locator('#notice').filter({hasText:'已保存'}).waitFor();
    await form.screenshot({path:'test-results/settings.png',fullPage:true});
    const pet=application.windows().find(p=>p.url().endsWith('pet.html'));
    assert.ok(pet);
    await form.locator('#close').click();
    await pet.locator('#pet').hover();
    assert.equal(await pet.locator('#card').isVisible(),false,'hover must never open income');
    await pet.locator('#pet').click();assert.equal(await pet.locator('#card').isVisible(),false,'left click must only trigger interaction');
    await toggleIncome(application,pet);await pet.locator('#card').waitFor({state:'visible'});
    assert.match(await pet.locator('#rate').textContent(),/¥\d/);
    await pet.screenshot({path:'test-results/pet-hover.png',omitBackground:true});
    await pet.locator('#card').hover();await new Promise(r=>setTimeout(r,300));
    assert.ok(await pet.locator('#card').isVisible(),'moving to card must not close it');
    await pet.mouse.move(2,2);await new Promise(r=>setTimeout(r,300));assert.ok(await pet.locator('#card').isVisible(),'income stays open until explicitly closed');
    await toggleIncome(application,pet);await pet.locator('#card').waitFor({state:'hidden'});
    await toggleIncome(application,pet);await pet.locator('#card').waitFor({state:'visible'});await pet.locator('#close-card').click();await pet.locator('#card').waitFor({state:'hidden'});
    const before=await application.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('pet.html')).getPosition());
    const box=await pet.locator('#pet').boundingBox();
    // CDP does not move the OS cursor; substitute only that input dependency.
    await application.evaluate(({screen})=>{globalThis.__realCursor=screen.getCursorScreenPoint;globalThis.__cursor={x:800,y:600};screen.getCursorScreenPoint=()=>({...globalThis.__cursor});});
    await pet.mouse.move(box.x+box.width/2,box.y+box.height/2);await pet.mouse.down();await pet.evaluate(()=>window.petAPI.getState());
    await application.evaluate(()=>{globalThis.__cursor={x:745,y:575};});
    await pet.mouse.move(box.x+box.width/2-55,box.y+box.height/2-25,{steps:8});await pet.mouse.up();
    await new Promise(r=>setTimeout(r,500));
    const after=await application.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('pet.html')).getPosition());
    assert.notDeepEqual(after,before,'dragging must move native window');
    await application.evaluate(({screen})=>{screen.getCursorScreenPoint=globalThis.__realCursor;});
    // After dragging, explicitly leave then reenter to test a new hover gesture.
    await pet.mouse.move(2,2);await pet.locator('#card').waitFor({state:'hidden'});
    await toggleIncome(application,pet);await pet.locator('#card').waitFor({state:'visible'});await pet.locator('#open-settings').click();
    const settings2=application.windows().find(p=>p.url().endsWith('settings.html'))??await application.waitForEvent('window').catch(()=>null);
    const form2=settings2||application.windows().find(p=>p.url().endsWith('settings.html'));
    await form2.locator('#salary').waitFor();assert.equal(await form2.locator('#salary').inputValue(),'10000.00');
    const today=await form2.evaluate(()=>{const d=new Date();return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`;});
    await form2.locator('#override-date').fill(today);await form2.locator('#override-type').selectOption('rest');await form2.locator('#add-override').click();await form2.locator('#save').click();
    await form2.locator('#notice').filter({hasText:'已保存'}).waitFor();
    const s=await form2.evaluate(()=>window.petAPI.getState());assert.equal(s.snapshot.earnedCents,0);assert.ok(['rest','empty'].includes(s.snapshot.status));
    await application.close();application=await launch();
    const restarted=await application.firstWindow();await restarted.waitForLoadState('domcontentloaded');
    const state=await restarted.evaluate(()=>window.petAPI.getState());assert.equal(state.config.salaryCents,1000000);assert.equal(state.config.overrides[today],false);
    const props=await application.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];return {top:w.isAlwaysOnTop(),preferences:w.webContents.getLastWebPreferences()};});
    assert.equal(props.top,true);assert.equal(props.preferences.nodeIntegration,false);assert.equal(props.preferences.contextIsolation,true);assert.equal(props.preferences.sandbox,true);assert.deepEqual(errors,[]);
    await fs.access('test-results/pet-hover.png');
    assert.equal(state.incomeVisible,false,'income starts hidden after restart');
    console.log('PASS: setup, validation, no hover/click income, native 查看 handler, explicit close, drag, reopen, date overrides and restart.');
  }finally{if(application)await application.close();await fs.rm(profile,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1;});
