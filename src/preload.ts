import {contextBridge,ipcRenderer} from 'electron';
import type {PetBridge} from './bridge.ts';
import type {DialogueLine} from './ai-dialogue.ts';
import type {AffinityPublic} from './affinity.ts';
const api:PetBridge={
  getState:()=>ipcRenderer.invoke('state'),
  save:(config,preferences)=>ipcRenderer.invoke('save',config,preferences),
  savePrefs:preferences=>ipcRenderer.invoke('prefs-save',preferences),
  setSize:size=>ipcRenderer.invoke('size',size),
  getAI:()=>ipcRenderer.invoke('ai-state'),
  saveAI:(config,key,removeKey)=>ipcRenderer.invoke('ai-save',config,key,removeKey),
  testAI:(config,key)=>ipcRenderer.invoke('ai-test',config,key),
  getChat:()=>ipcRenderer.invoke('chat-state'),
  sendChat:text=>ipcRenderer.invoke('chat-send',text),
  actionReply:action=>ipcRenderer.invoke('ai-action',action),
  clearChat:()=>ipcRenderer.invoke('chat-clear'),
  openChat:()=>ipcRenderer.send('chat-open'),
  hideIncome:()=>ipcRenderer.send('income-hide'),
  onSpeech:listener=>{ipcRenderer.on('speech',(_event,text:unknown)=>{if(typeof text==='string')listener(text);});},
  onDialogue:listener=>{ipcRenderer.on('dialogue',(_event,lines:unknown)=>{if(Array.isArray(lines)&&lines.length>=2&&lines.every(line=>line&&typeof line==='object'&&typeof (line as {text?:unknown}).text==='string'&&((line as {who?:unknown}).who==='yier'||(line as {who?:unknown}).who==='bubu')))listener(lines as DialogueLine[]);});},
  getAffinity:()=>ipcRenderer.invoke('affinity-state'),
  affinityEvent:(type,meta)=>ipcRenderer.invoke('affinity-event',type,meta),
  setBirthday:value=>ipcRenderer.invoke('affinity-birthday',value),
  onAffinity:listener=>{ipcRenderer.on('affinity',(_event,state:unknown)=>{if(state&&typeof state==='object')listener(state as AffinityPublic);});},
  onAffinityToast:listener=>{ipcRenderer.on('affinity-toast',(_event,text:unknown)=>{if(typeof text==='string')listener(text);});},
  onEggAction:listener=>{ipcRenderer.on('egg-action',(_event,egg:unknown)=>{if(typeof egg==='string')listener(egg);});},
  onFeed:listener=>{ipcRenderer.on('feed',(_event,snack:unknown)=>{if(typeof snack==='string')listener(snack);});},
  onWander:listener=>{ipcRenderer.on('wander',(_event,direction:unknown)=>{if(typeof direction==='string')listener(direction);});},
  getVoice:()=>ipcRenderer.invoke('voice-state'),
  saveVoice:(config,key,removeKey)=>ipcRenderer.invoke('voice-save',config,key,removeKey),
  testVoice:who=>ipcRenderer.invoke('voice-test',who),
  createQwenVoices:()=>ipcRenderer.invoke('voice-create-qwen'),
  createCustomVoice:input=>ipcRenderer.invoke('voice-create-custom',input),
  assignVoice:(entryId,target)=>ipcRenderer.invoke('voice-assign',entryId,target),
  deleteVoice:entryId=>ipcRenderer.invoke('voice-delete',entryId),
  previewVoice:entryId=>ipcRenderer.invoke('voice-preview',entryId),
  speakLine:(who,text)=>ipcRenderer.invoke('voice-speak',who,text),
  openSettings:()=>ipcRenderer.send('settings'),
  closeSettings:()=>ipcRenderer.send('close-settings'),
  menu:()=>ipcRenderer.send('menu'),
  passthrough:ignore=>ipcRenderer.send('passthrough',ignore),
  drag:action=>ipcRenderer.send('drag',action),
  onChanged:listener=>{ipcRenderer.on('changed',()=>listener());}
};
contextBridge.exposeInMainWorld('petAPI',api);
